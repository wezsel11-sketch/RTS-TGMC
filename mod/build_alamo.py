"""The Alamo's sprite: one image of the whole dropship, drawn from its pieces (see the Alamo design spec).

Each piece of the dmm is a dropship_piece subtype. Its icon_state comes from its definition in TGMC's marine_dropship.dm
(the `icon_state = "..."` line under its path). Each cell is pasted at 32 px, in the dmm's layout, into one image of
11 x 21 cells: sprites/alamo.png, with the sequence `idle` for the actor to show.
"""
import os
import re

from PIL import Image, PngImagePlugin

import tgmc_dmi
import tgmc_dmm

DROPSHIP_DM = os.path.join("code", "modules", "shuttle", "marine_dropship.dm")
DROPSHIP_DMI = os.path.join("icons", "obj", "structures", "dropship_structures.dmi")
ALAMO_DMM = os.path.join("_maps", "shuttles", "alamo.dmm")
CELL = 32


def icon_states(tgmc):
    """{piece path: icon_state} from TGMC's dropship code: each `/obj/structure/dropship_piece/...` header, then its icon_state."""
    text = open(os.path.join(tgmc, DROPSHIP_DM), encoding="utf-8").read()
    states, path = {}, None
    for line in text.split("\n"):
        m = re.match(r"^(/obj/structure/dropship_piece/[\w/]+)\s*$", line)
        if m:
            path = m.group(1)
            continue
        m = re.match(r'^\ticon_state = "([\w]+)"', line)
        if m and path:
            states[path] = m.group(1)
            path = None
    return states


def build(tgmc, out):
    """Write sprites/alamo.png and sequences/alamo.yaml. Returns the image size in cells."""
    dmm = os.path.join(tgmc, ALAMO_DMM)
    width, height, grid = tgmc_dmm.parse(dmm)
    _, _, things = tgmc_dmm.parse_objects(dmm)
    states = icon_states(tgmc)
    dmi = tgmc_dmi.Dmi(os.path.join(tgmc, DROPSHIP_DMI))

    cells = []
    for x in range(width):
        for y in range(height):
            for path, _ in things[x][y]:
                if path.startswith("/obj/structure/dropship_piece/") and path in states:
                    cells.append((x, y, states[path]))
    if not cells:
        raise SystemExit("alamo: no dropship pieces found in " + dmm)
    ox = min(x for x, _, _ in cells)
    oy = min(y for _, y, _ in cells)
    cols = max(x for x, _, _ in cells) - ox + 1
    rows = max(y for _, y, _ in cells) - oy + 1

    img = Image.new("RGBA", (cols * CELL, rows * CELL), (0, 0, 0, 0))
    for x, y, state in cells:
        frame = dmi.frames(state)[0][0].convert("RGBA")
        img.alpha_composite(frame.crop((0, 0, CELL, CELL)), ((x - ox) * CELL, (y - oy) * CELL))

    os.makedirs(os.path.join(out, "sprites"), exist_ok=True)
    meta = PngImagePlugin.PngInfo()
    meta.add_text("FrameSize", f"{cols * CELL},{rows * CELL}")
    meta.add_text("FrameAmount", "1")
    img.save(os.path.join(out, "sprites", "alamo.png"), pnginfo=meta)

    os.makedirs(os.path.join(out, "sequences"), exist_ok=True)
    with open(os.path.join(out, "sequences", "alamo.yaml"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by mod/build_alamo.py. Do not edit.\nalamo:\n\tDefaults:\n\t\tFilename: sprites/alamo.png\n\tidle:\n\t\tStart: 0\n")
    return cols, rows
